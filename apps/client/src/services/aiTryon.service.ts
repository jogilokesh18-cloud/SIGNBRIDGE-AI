/**
 * AURA AI — Generative Virtual Try-On Client Service
 *
 * Sends person photo + garment photo to the backend, which uses
 * Gemini AI image generation to EDIT the person's photo so they
 * appear naturally wearing the garment. No canvas overlay, no
 * cut-and-paste — the AI redraws the person wearing the clothing.
 */

export interface TryonGenerationResult {
  /** Data URL of the AI-generated photo (person wearing the garment). */
  synthesizedImageUrl: string;
  /** Original person photo URL for before/after comparison. */
  originalImageUrl: string;
  /** Garment photo URL. */
  garmentImageUrl: string;
  /** AI styling notes. */
  stylingNotes: string;
  /** Whether the result was generated by AI (true) or fallback canvas (false). */
  isAiGenerated: boolean;
}

const API_BASE = '/api/v1';

export class AiTryonService {
  /**
   * Sends both images to the server for Gemini-powered photo editing.
   * The AI edits the person's photo to show them genuinely wearing the garment.
   */
  async synthesizeTryon(
    personPhotoSrc: string,
    garmentPhotoSrc: string,
    options?: {
      garmentName?: string;
      garmentDescription?: string;
      selectedSize?: string;
    }
  ): Promise<TryonGenerationResult> {
    // Convert both image sources to base64
    const [personData, garmentData] = await Promise.all([
      this.imageToBase64(personPhotoSrc),
      this.imageToBase64(garmentPhotoSrc)
    ]);

    try {
      const response = await fetch(`${API_BASE}/tryon/generate`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          personImageBase64: personData.base64,
          personImageMimeType: personData.mimeType,
          garmentImageBase64: garmentData.base64,
          garmentImageMimeType: garmentData.mimeType,
          garmentName: options?.garmentName || 'clothing item',
          garmentDescription: options?.garmentDescription || ''
        })
      });

      const body = await response.json();

      if (!response.ok || !body.success) {
        throw new Error(body?.error?.message || 'Try-on generation failed');
      }

      const resultBase64 = body.data.resultImageBase64;
      const resultMime = body.data.resultMimeType || 'image/png';
      const synthesizedDataUrl = `data:${resultMime};base64,${resultBase64}`;

      return {
        synthesizedImageUrl: synthesizedDataUrl,
        originalImageUrl: personPhotoSrc,
        garmentImageUrl: garmentPhotoSrc,
        stylingNotes: body.data.stylingNotes || 'AI virtual try-on complete.',
        isAiGenerated: true
      };
    } catch (err) {
      console.error('AI try-on service error, using canvas fallback:', err);
      // Fallback to client-side canvas composite if Gemini fails
      return this.canvasFallback(personPhotoSrc, garmentPhotoSrc, options);
    }
  }

  /**
   * Converts an image URL (including data URLs, blob URLs, and HTTP URLs)
   * to a { base64, mimeType } object by drawing onto a canvas.
   */
  private async imageToBase64(
    src: string
  ): Promise<{ base64: string; mimeType: string }> {
    // If it's already a data URL, extract the base64 directly
    if (src.startsWith('data:')) {
      const match = src.match(/^data:([^;]+);base64,(.+)$/);
      if (match) {
        return { base64: match[2], mimeType: match[1] };
      }
    }

    // Otherwise, load image onto canvas and export
    const img = await this.loadImage(src);
    const canvas = document.createElement('canvas');
    // Cap resolution to reduce payload size
    const maxDim = 1024;
    let w = img.naturalWidth;
    let h = img.naturalHeight;
    if (w > maxDim || h > maxDim) {
      const scale = maxDim / Math.max(w, h);
      w = Math.round(w * scale);
      h = Math.round(h * scale);
    }
    canvas.width = w;
    canvas.height = h;
    const ctx = canvas.getContext('2d')!;
    ctx.drawImage(img, 0, 0, w, h);
    const dataUrl = canvas.toDataURL('image/jpeg', 0.85);
    const match = dataUrl.match(/^data:([^;]+);base64,(.+)$/);
    return {
      base64: match ? match[2] : '',
      mimeType: match ? match[1] : 'image/jpeg'
    };
  }

  /**
   * Canvas-based fallback: draws the garment over the person photo with
   * blending. Used only when the Gemini API is unavailable.
   */
  private async canvasFallback(
    personPhotoSrc: string,
    garmentPhotoSrc: string,
    options?: { garmentName?: string; selectedSize?: string }
  ): Promise<TryonGenerationResult> {
    const [personImg, garmentImg] = await Promise.all([
      this.loadImage(personPhotoSrc),
      this.loadImage(garmentPhotoSrc)
    ]);

    const canvas = document.createElement('canvas');
    canvas.width = Math.min(1920, Math.max(1024, personImg.naturalWidth || 1280));
    canvas.height = Math.round(
      canvas.width * ((personImg.naturalHeight || 960) / (personImg.naturalWidth || 1280))
    );
    const ctx = canvas.getContext('2d')!;
    const width = canvas.width;
    const height = canvas.height;

    // Draw person
    ctx.drawImage(personImg, 0, 0, width, height);

    // Anatomical region estimate
    const cx = width / 2;
    const neckY = height * 0.34;
    const shoulderY = height * 0.40;
    const shoulderSpan = width * 0.48;
    const waistY = height * 0.68;
    const waistWidth = shoulderSpan * 0.76;
    const hemY = height * 0.82;
    const hemWidth = shoulderSpan * 0.88;

    ctx.save();
    ctx.shadowColor = 'rgba(0, 0, 0, 0.55)';
    ctx.shadowBlur = 25;
    ctx.shadowOffsetY = 10;

    // Torso clipping path
    ctx.beginPath();
    ctx.moveTo(cx - width * 0.07, neckY);
    ctx.quadraticCurveTo(cx, neckY + 16, cx + width * 0.07, neckY);
    ctx.quadraticCurveTo(cx + shoulderSpan * 0.32, shoulderY - 8, cx + shoulderSpan * 0.52, shoulderY + 15);
    ctx.quadraticCurveTo(cx + waistWidth * 0.54, waistY * 0.85, cx + waistWidth * 0.50, waistY);
    ctx.lineTo(cx + hemWidth * 0.50, hemY);
    ctx.quadraticCurveTo(cx, hemY + 18, cx - hemWidth * 0.50, hemY);
    ctx.lineTo(cx - waistWidth * 0.50, waistY);
    ctx.quadraticCurveTo(cx - waistWidth * 0.54, waistY * 0.85, cx - shoulderSpan * 0.52, shoulderY + 15);
    ctx.quadraticCurveTo(cx - shoulderSpan * 0.32, shoulderY - 8, cx - width * 0.07, neckY);
    ctx.closePath();
    ctx.clip();

    const gWidth = shoulderSpan * 1.35;
    const gHeight = (gWidth * (garmentImg.naturalHeight || 600)) / (garmentImg.naturalWidth || 500);
    ctx.globalAlpha = 0.92;
    ctx.drawImage(garmentImg, cx - gWidth / 2, neckY - 10, gWidth, gHeight);
    ctx.restore();

    return {
      synthesizedImageUrl: canvas.toDataURL('image/jpeg', 0.94),
      originalImageUrl: personPhotoSrc,
      garmentImageUrl: garmentPhotoSrc,
      stylingNotes:
        'Fallback mode: canvas composite used because AI generation was unavailable. For best results, ensure GEMINI_API_KEY is configured.',
      isAiGenerated: false
    };
  }

  private loadImage(src: string): Promise<HTMLImageElement> {
    return new Promise((resolve, reject) => {
      const img = new Image();
      img.crossOrigin = 'anonymous';
      img.onload = () => resolve(img);
      img.onerror = (e) =>
        reject(new Error(`Failed to load image: ${e}`));
      img.src = src;
    });
  }
}

export const aiTryonService = new AiTryonService();
